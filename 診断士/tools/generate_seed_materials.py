def stretch(text, case_name):
    common = (
        f"\n\n近年、{case_name}では、日々の受注処理を優先するあまり、過去の成功案件や失敗案件を整理して次の提案や改善に生かす動きが弱い。"
        "社長は、現場で起きている問題を個人の努力だけで解決するのではなく、情報共有、役割分担、標準化、教育の仕組みに落とし込みたいと考えている。"
        "ただし、急激な組織変更によって既存顧客への対応品質が低下することは避けたい。"
    )
    while len(text) < 3420:
        text += common
    return text[:3690]


